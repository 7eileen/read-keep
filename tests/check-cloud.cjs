const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const modulePath = path.join(__dirname, '../dist/cloud-core.js');
assert.ok(fs.existsSync(modulePath), 'Cloud sync core is implemented');
const C = require(modulePath);
const blank = () => ({articles: [], entries: [], settings: {interval:3,batch:5,autoTranslate:true}});
const a = {id:'a',title:'Article',paragraphs:[{text:'Cities adapt.'}]};
const e = {id:'e',word:'adapt',meaning:'适应',due:'2026-10-13'};
const base = {...blank(),articles:[a],entries:[e]};
const local = {...base,entries:[{...e,note:'mine'}]};
const remote = {...base,articles:[{...a,title:'Other device'}]};
let r = C.merge(base,local,remote);
assert.equal(r.conflicts.length,0);
assert.equal(r.state.articles[0].title,'Other device');
assert.equal(r.state.entries[0].note,'mine');
assert.equal(C.merge(base,local,{...base,entries:[{...e,note:'theirs'}]}).conflicts.length,1);
assert.equal(C.merge(base,local,{...base,entries:[]}).conflicts.length,1,'Deletion versus edit is a conflict');
assert.equal(C.merge(base,{...base,entries:[]},{...base,entries:[]}).conflicts.length,0);
assert.equal(C.merge(base,local,{...base,entries:[{...e,note:'theirs'}]},'remote').state.entries[0].note,'theirs');
assert.equal(C.merge(base,local,{...base,entries:[{...e,note:'theirs'}]},'local').state.entries[0].note,'mine');
assert.equal(C.changes(base,local,{'entries:e':4})[0].version,4);
assert.equal(C.changes(base,{...base,entries:[]},{'entries:e':4})[0].data,null);
assert.equal(C.changes(blank(),base,{})[0].version,null);
const guest={...base,entries:[e,{...e,id:'demo',sample:true}]};
assert.equal(C.migrate(blank(),guest).entries.length,1);
assert.equal(C.migrate(C.migrate(blank(),guest),guest).entries.length,1,'Repeated migration is idempotent');
assert.throws(()=>C.migrate({...base,entries:[{...e,meaning:'different'}]},guest),/冲突/);
assert.equal(C.merge(base,{...local,entries:[{...e,note:'new edit'}]},local).state.entries[0].note,'new edit','Edits while saving survive acknowledgement');
assert.notEqual(C.accountKey('a'),C.accountKey('b'));
assert.notEqual(C.accountKey('a'),'read-and-keep-demo-v1');
console.log('PASS: sync merge, conflicts, revision guards, delete, migration and account namespaces.');

const assert=require('node:assert/strict');
const C=require('../dist/core.js');
const fixed='2026-10-09';
assert.equal(C.addDays('2026-12-31',1),'2027-01-01');
assert.equal(C.addDays('2028-02-28',1),'2028-02-29');
assert.equal(C.addDays('2026-03-01',-1),'2026-02-28');
const parsed=C.parseBatch('in the long run | 长期来看 | In the long run, it helps.\n\nretain');
assert.equal(parsed.length,2);assert.equal(parsed[0].word,'in the long run');
const first=C.addEntries([],parsed,'Article A',fixed);assert.equal(first.added,2);
assert.equal(first.entries[0].due,'2026-10-10');
assert.equal(C.addEntries(first.entries,parsed,'Article A',fixed).added,0);
assert.equal(C.addEntries(first.entries,parsed,'Article B',fixed).added,2);
assert.equal(C.addEntries(first.entries,[{word:'retain',sentence:'Another context.'}],'Article A',fixed).added,1);
const sample=C.seed(fixed);assert.equal(C.dueEntries(sample,fixed).length,5);
const read=C.reviewed(sample[0],'read',3,fixed);assert.equal(read.due,'2026-10-12');assert.equal(read.reviews,1);
const less=C.reviewed(sample[0],'less',3,fixed);assert.equal(less.due,'2026-10-16');assert.equal(less.star,false);assert.equal(less.level,'familiar');
const again=C.reviewed(sample[0],'again',3,fixed);assert.equal(again.due,'2026-10-10');assert.equal(again.star,true);
assert.equal(C.dueEntries([read,less,again],fixed).length,0);
console.log('PASS: 日期跨月跨年、批量输入、同语境去重、多语境保留、回顾排期与待回顾筛选。');
